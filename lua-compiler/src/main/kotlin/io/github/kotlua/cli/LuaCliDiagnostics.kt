package io.github.kotlua.cli

import org.jetbrains.kotlin.diagnostics.KtDiagnosticFactoryToRendererMap
import org.jetbrains.kotlin.diagnostics.KtDiagnosticsContainer
import org.jetbrains.kotlin.diagnostics.KtSourcelessDiagnosticFactory
import org.jetbrains.kotlin.diagnostics.errorWithoutSource
import org.jetbrains.kotlin.diagnostics.rendering.BaseDiagnosticRendererFactory
import org.jetbrains.kotlin.diagnostics.rendering.BaseSourcelessDiagnosticRendererFactory
import org.jetbrains.kotlin.diagnostics.strongWarningWithoutSource

@Suppress("standard:property-naming")
object LuaCliDiagnostics : KtDiagnosticsContainer() {
    val LUA_ARGUMENT_ERROR: KtSourcelessDiagnosticFactory by errorWithoutSource()
    val LUA_ARGUMENT_WARNING: KtSourcelessDiagnosticFactory by strongWarningWithoutSource()

    override fun getRendererFactory(): BaseDiagnosticRendererFactory = Messages

    object Messages : BaseSourcelessDiagnosticRendererFactory() {
        override val MAP: KtDiagnosticFactoryToRendererMap by KtDiagnosticFactoryToRendererMap("LUA") { map ->
            map.put(LUA_ARGUMENT_ERROR, MESSAGE_PLACEHOLDER)
            map.put(LUA_ARGUMENT_WARNING, MESSAGE_PLACEHOLDER)
        }
    }
}
